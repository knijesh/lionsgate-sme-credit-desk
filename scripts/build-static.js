// Builds the public, server-free version of the desk into docs/ (served by GitHub Pages).
// The same engine, desk and routes run in the visitor's browser; each visitor gets a private desk.
//   node scripts/build-static.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), OUT = path.join(ROOT, 'docs');
// Node built-ins the desk touches. path is only used by evals/run.js's command-line block, never in the browser.
const SHIMS = { crypto: 'scripts/sha256-shim.js', path: 'shim:empty' };

// Collect lib/routes.js and everything it requires, resolving each require to a repo-relative id.
const mods = {};
function add(id) {
  if (mods[id]) return;
  if (id === 'shim:empty') { mods[id] = { src: 'module.exports = {};', deps: {} }; return; }
  const src = fs.readFileSync(path.join(ROOT, id), 'utf8');
  mods[id] = { src, deps: {} };
  if (id.endsWith('.json')) return;
  for (const [, spec] of src.matchAll(/require\(['"]([^'"]+)['"]\)/g)) {
    let dep = SHIMS[spec];
    if (!dep) {
      if (!spec.startsWith('.')) throw new Error(`${id}: cannot bundle "${spec}" for the browser`);
      dep = path.relative(ROOT, path.resolve(path.dirname(path.join(ROOT, id)), spec));
      if (!fs.existsSync(path.join(ROOT, dep))) dep += '.js';
    }
    mods[id].deps[spec] = dep;
    add(dep);
  }
}
add('lib/routes.js');

const defs = Object.entries(mods).map(([id, m]) => {
  const body = id.endsWith('.json') ? `module.exports = ${m.src.trim()};` : m.src;
  return `${JSON.stringify(id)}: [${JSON.stringify(m.deps)}, function (module, exports, require) {\n${body}\n}]`;
}).join(',\n');

const bundle = `// Generated by scripts/build-static.js — do not edit.
(function () {
  const defs = {\n${defs}\n};
  const cache = {};
  function load(id) {
    if (cache[id]) return cache[id].exports;
    const [deps, fn] = defs[id], module = (cache[id] = { exports: {} });
    fn(module, module.exports, spec => load(deps[spec]));
    return module.exports;
  }
  const routes = load('lib/routes.js'), desk = load('lib/desk.js');
  // Same contract as fetch() against the server: JSON in, JSON out, errors carry the message.
  window.LocalDesk = {
    async call(method, url, body) {
      for (const [m, re, fn] of routes) {
        const match = url.match(re);
        if (match && m === method) return JSON.parse(JSON.stringify(await fn(match, body || {})));
      }
      throw new Error('Not found');
    },
    // Stand-in for the server-sent event stream: desk.emit() writes SSE frames to each client.
    subscribe(handler) {
      desk.S.clients.add({ write(frame) {
        const ev = /^event: (.+)$/m.exec(frame), data = /^data: (.+)$/m.exec(frame);
        if (ev && data) handler(ev[1], JSON.parse(data[1]));
      } });
    },
  };
  desk.startSimulation();
})();
`;

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT);
fs.writeFileSync(path.join(OUT, 'desk.bundle.js'), bundle);
for (const f of ['app.js', 'app.css']) fs.copyFileSync(path.join(ROOT, 'public', f), path.join(OUT, f));
const html = fs.readFileSync(path.join(ROOT, 'public/index.html'), 'utf8')
  .replace(/\/app\.(css|js)/g, 'app.$1')
  .replace('<script src="app.js"></script>', '<script src="desk.bundle.js"></script>\n<script src="app.js"></script>');
fs.writeFileSync(path.join(OUT, 'index.html'), html);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
if (process.env.CNAME) fs.writeFileSync(path.join(OUT, 'CNAME'), process.env.CNAME + '\n');
console.log(`docs/: ${Object.keys(mods).length} modules bundled · ${(Buffer.byteLength(bundle) / 1024).toFixed(0)} KB`);
